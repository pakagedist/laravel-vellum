<?php

declare(strict_types=1);

namespace Vellum\Drivers;

use Vellum\Config\ResolvedConfig;
use Vellum\Contracts\Capability;
use Vellum\Contracts\Driver;
use Vellum\Contracts\Source;
use Vellum\Support\Pdf\MiniPdf;

/**
 * A driver that never renders anything.
 *
 * It returns a deterministic, valid PDF and records every call so the
 * application can be tested without a real engine.
 */
final class FakeDriver implements Driver
{
    /**
     * @var list<array{source: string, description: string, driver: string, paper: string, orientation: string}>
     */
    private array $calls = [];

    public function name(): string
    {
        return 'fake';
    }

    /**
     * @return list<string>
     */
    public function capabilities(): array
    {
        return Capability::all();
    }

    public function supports(string $capability): bool
    {
        return in_array($capability, $this->capabilities(), true);
    }

    public function render(Source $source, ResolvedConfig $config): string
    {
        // The source is still resolved so a missing view, file or URL is
        // reported even when nothing is actually rendered.
        $source->load($config);

        $this->calls[] = [
            'source' => $source->type(),
            'description' => $source->describe(),
            'driver' => $config->driver,
            'paper' => $config->paper->value,
            'orientation' => $config->orientation->value,
        ];

        return MiniPdf::create(sprintf(
            'Fake PDF generated by the Vellum package (%s source).',
            $source->type(),
        ));
    }

    /**
     * @return list<array{source: string, description: string, driver: string, paper: string, orientation: string}>
     */
    public function calls(): array
    {
        return $this->calls;
    }

    public function reset(): void
    {
        $this->calls = [];
    }
}
